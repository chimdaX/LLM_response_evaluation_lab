"""Interactive human annotation: single-response evaluations and pairwise preferences.

Design choices that protect benchmark integrity:

* **Blind review.** Model and provider names are never shown while annotating, so
  brand expectations cannot influence scores.
* **Requirements first.** The prompt is shown before the response, and the reviewer
  presses Enter to reveal the response after reading the requirements.
* **Human attestation.** Each session starts with a confirmation that the judgments
  are the reviewer's own; only then are records saved with ``annotation_source: human``.
* **Append-only, resumable.** Every answer is saved to a draft immediately; the final
  record is validated against the schema and appended atomically. Existing records
  are never modified, and the same reviewer cannot evaluate the same response twice
  unless a consistency re-review is explicitly requested.
"""

