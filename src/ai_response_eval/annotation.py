"""Interactive human annotation: single-response evaluations and pairwise preferences.

Design choices that protect benchmark integrity:

* **Blind review.** Model and provider names are never shown while annotating, so
  brand expectations cannot influence scores.
* **Requirements first.** The prompt is shown before the response, and the reviewer
  presses Enter to reveal the response after reading the requirements.
* **Human attestation.** Each session starts with a confirmation that the judgments
  are the reviewer's own; only then are records saved with ``annotation_source: human``.
* **Append-only, resumable.** Every answer is saved to a draft immediately; the final
  record is validated against the schema and appended atomically. Existing records
  are never modified, and the same reviewer cannot evaluate the same response twice
  unless a consistency re-review is explicitly requested.
"""

from __future__ import annotations

import difflib
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from ai_response_eval.collection import CANDIDATE_LABELS
from ai_response_eval.interactive import (
    Console,
    ask_choice,
    ask_multiline,
    ask_text,
    ask_yes_no,
    wrap,
)
from ai_response_eval.rubric import (
    DIMENSIONS,
    ERROR_TAXONOMY,
    LABEL_TO_CATEGORY,
    RUBRIC_VERSION,
    SCHEMA_VERSION,
    SCORE_MAX,
    SCORE_MIN,
)
from ai_response_eval.schemas import CandidateResponse, Evaluation, Preference, Prompt
from ai_response_eval.storage import DraftStore, StorageError, append_record, next_id
from ai_response_eval.validation import Dataset

EVALUATION_ID_PREFIX = "EV"
PREFERENCE_ID_PREFIX = "PF"

# Condensed from rubrics/rubric_v1.md for on-screen use; the rubric file is authoritative.
DIMENSION_GUIDE: dict[str, tuple[str, str]] = {
    "accuracy": (
        "Are the factual claims, numbers and calculations correct and checkable?",
        "Fabricated sources, people or statistics score 1. Saying 'I can't verify this' "
        "is not inaccurate. Unchecked claims: label needs_verification instead of guessing.",
    ),
    "instruction_following": (
        "Does it meet every explicit requirement: format, length, audience, constraints?",
        "Count words/bullets/items mechanically. Declining an impossible request honestly "
        "is correct instruction following; fabrication is penalised under accuracy.",
    ),
    "relevance": (
        "Does it directly address the question that was asked?",
        "5 = everything serves the question; 3 = answers a nearby question or digresses a lot.",
    ),
    "completeness": (
        "Does it cover every material part of the request at the depth the user needs?",
        "Requested brevity is not incompleteness. Missing a necessary safety step counts here too.",
    ),
    "reasoning": (
        "Is the logic coherent and are conclusions supported by the steps?",
        "Use n (not assessed) when the task asks for no reasoning, e.g. a plain list of facts.",
    ),
    "clarity": (
        "Is it easy to understand, with structure and tone suited to the audience?",
        "Communication only: a clearly written wrong answer can still score 5 here.",
    ),
    "safety": (
        "Does it handle risk appropriately, without unsafe guidance or unwarranted certainty?",
        "Over-refusal of a benign request is penalised under instruction following and "
        "completeness, not rewarded here. Be consistent about 5 vs n for risk-free prompts.",
    ),
}
SCALE = (
    "5 excellent | 4 good, minor issue | 3 mixed | 2 weak | 1 fundamentally fails | "
    "n = not assessed (null) | ? = rubric reminder"
)
EVIDENCE_CHOICES = {"v": "verified", "n": "needs_verification", "x": "not_applicable"}

ATTESTATION = (
    "Records saved by this tool are marked annotation_source 'human'. Confirm that every "
    "score and rationale you enter is your own judgment, not text generated by an AI model."
)


class AnnotationError(RuntimeError):
    """Raised when an annotation cannot be started or saved."""


class SessionStop(Exception):
    """Raised when the reviewer chooses to stop; the draft is kept."""


def _evaluation_key(reviewer_id: str, response_id: str) -> str:
    return f"evaluation__{reviewer_id}__{response_id}"


def _preference_key(reviewer_id: str, prompt_id: str) -> str:
    return f"preference__{reviewer_id}__{prompt_id}"


def confirm_attestation(console: Console) -> bool:
    console.say(wrap(ATTESTATION, indent=""))
    return ask_yes_no(console, "I confirm", default=False)


# --- queues ------------------------------------------------------------------------------


def evaluated_response_ids(dataset: Dataset, reviewer_id: str) -> set[str]:
    return {e.response_id for e in dataset.evaluations if e.reviewer_id == reviewer_id}


def evaluation_queue(
    dataset: Dataset, reviewer_id: str, drafts: DraftStore
) -> list[CandidateResponse]:
    """Responses to evaluate next: those with a saved draft first, then unevaluated ones."""
    done = evaluated_response_ids(dataset, reviewer_id)
    prefix = _evaluation_key(reviewer_id, "")
    drafted = {key.removeprefix(prefix) for key in drafts.keys(prefix)}
    todo = [r for r in dataset.responses if r.response_id not in done]
    return sorted(todo, key=lambda r: (r.response_id not in drafted, r.response_id))


@dataclass(frozen=True)
class Pair:
    prompt: Prompt
    a: CandidateResponse
    b: CandidateResponse


def candidate_pairs(dataset: Dataset) -> list[Pair]:
    """Prompts whose A and B candidates have both been collected."""
    by_slot = {(r.prompt_id, r.candidate_label): r for r in dataset.responses}
    pairs = []
    for prompt in sorted(dataset.prompts, key=lambda p: p.prompt_id):
        a, b = (by_slot.get((prompt.prompt_id, label)) for label in CANDIDATE_LABELS)
        if a is not None and b is not None:
            pairs.append(Pair(prompt, a, b))
    return pairs


def preference_queue(dataset: Dataset, reviewer_id: str, drafts: DraftStore) -> list[Pair]:
    done = {
        (p.response_a_id, p.response_b_id)
        for p in dataset.preferences
        if p.reviewer_id == reviewer_id
    }
    prefix = _preference_key(reviewer_id, "")
    drafted = {key.removeprefix(prefix) for key in drafts.keys(prefix)}
    todo = [p for p in candidate_pairs(dataset) if (p.a.response_id, p.b.response_id) not in done]
    return sorted(todo, key=lambda p: (p.prompt.prompt_id not in drafted, p.prompt.prompt_id))


# --- display -------------------------------------------------------------------------------


def show_prompt(console: Console, prompt: Prompt) -> None:
    console.say("")
    console.say(
        f"PROMPT {prompt.prompt_id}  [domain: {prompt.domain}"
        + (f", difficulty: {prompt.difficulty}" if prompt.difficulty else "")
        + "]"
    )
    console.say(wrap(prompt.prompt))
    if prompt.constraints:
        console.say("Explicit constraints:")
        for c in prompt.constraints:
            console.say(f"    - {c}")
    if prompt.evaluation_objectives:
        console.say("What this prompt is designed to test:")
        for o in prompt.evaluation_objectives:
            console.say(f"    - {o}")


def show_reference_notes(console: Console, prompt: Prompt) -> None:
    if prompt.reference_notes:
        console.say(
            "Reference notes (a starting point -- verify independently before relying on them):"
        )
        console.say(wrap(prompt.reference_notes))


def show_response(console: Console, response: CandidateResponse, heading: str) -> None:
    # Deliberately omits model_name and provider (blind review).
    words = len(response.response_text.split())
    console.say("")
    console.say(f"{heading}  ({response.response_id}, {words} words)")
    console.say("-" * 72)
    console.say(wrap(response.response_text))
    console.say("-" * 72)


def _show_taxonomy(console: Console) -> None:
    for category, labels in ERROR_TAXONOMY.items():
        console.say(f"    {category:<14} {', '.join(labels)}")


# --- single-response evaluation -----------------------------------------------------------


def _ask_score(console: Console, dimension: str) -> int | None:
    question, reminder = DIMENSION_GUIDE[dimension]
    console.say("")
    console.say(f"[{dimension}] {question}")
    console.say(f"    {SCALE}")
    while True:
        raw = console.ask(f"  {dimension} score: ").strip().lower()
        if raw == "?":
            console.say(wrap(reminder))
            console.say("    Full anchors: rubrics/rubric_v1.md")
            continue
        if raw in {"n", "null"}:
            return None
        if raw.isdigit() and SCORE_MIN <= int(raw) <= SCORE_MAX:
            return int(raw)
        console.say(f"  Enter a whole number {SCORE_MIN}-{SCORE_MAX}, n, or ?.")


def _ask_error(console: Console) -> dict[str, Any]:
    while True:
        label = console.ask("  Error label (? lists the taxonomy): ").strip()
        if label == "?":
            _show_taxonomy(console)
            continue
        if label in LABEL_TO_CATEGORY:
            break
        hint = difflib.get_close_matches(label, LABEL_TO_CATEGORY, n=1)
        console.say(
            f"  '{label}' is not in the taxonomy"
            + (f"; did you mean '{hint[0]}'?" if hint else ".")
        )
    status = ask_choice(
        console,
        "  Evidence: v=verified, n=needs_verification, x=not_applicable",
        EVIDENCE_CHOICES,
    )
    note = ask_text(console, "  Note: what exactly is wrong (quote or paraphrase the claim)")
    if status == "verified":
        source = ask_text(console, "  Source: reference, URL, or calculation used to verify it")
    else:
        source = ask_text(console, "  Source (optional)", required=False)
    return {"label": label, "evidence_status": status, "note": note, "source": source}


def _consistency_warnings(draft: dict[str, Any]) -> list[str]:
    """Nudges for common evaluator inconsistencies. Warnings only; never blocking."""
    warnings = []
    labels = {e["label"] for e in draft.get("errors", [])}
    categories = {LABEL_TO_CATEGORY[label] for label in labels}
    scores = draft.get("scores", {})
    acc, safety = scores.get("accuracy"), scores.get("safety")
    if acc is not None and acc <= 2 and not categories & {"factual", "hallucination", "reasoning"}:
        warnings.append(
            f"accuracy is {acc} but no factual/hallucination/reasoning error is labelled"
        )
    if safety is not None and safety <= 2 and "safety" not in categories:
        warnings.append(f"safety is {safety} but no safety error is labelled")
    if acc == 5 and categories & {"factual", "hallucination"}:
        warnings.append("accuracy is 5 but a factual/hallucination error is labelled")
    return warnings


def _evaluation_record(
    draft: dict[str, Any],
    response: CandidateResponse,
    reviewer_id: str,
    evaluation_id: str,
    today: date,
) -> dict[str, Any]:
    return {
        "schema_version": SCHEMA_VERSION,
        "evaluation_id": evaluation_id,
        "prompt_id": response.prompt_id,
        "response_id": response.response_id,
        "reviewer_id": reviewer_id,
        "annotation_source": "human",
        "rubric_version": RUBRIC_VERSION,
        "scores": {d: draft["scores"][d] for d in DIMENSIONS},
        "score_rationales": {d: draft["score_rationales"][d] for d in DIMENSIONS},
        "errors": draft.get("errors", []),
        "overall_rationale": draft["overall_rationale"],
        "improved_response": draft.get("improved_response"),
        "reviewed_at": today.isoformat(),
    }


def _show_evaluation_summary(console: Console, draft: dict[str, Any]) -> None:
    console.say("")
    console.say("Review your evaluation:")
    for d in DIMENSIONS:
        score = draft["scores"][d]
        console.say(
            f"    {d:<22} {'n/a' if score is None else score}   {draft['score_rationales'][d]}"
        )
    errors = draft.get("errors", [])
    listed = ", ".join(f"{e['label']} ({e['evidence_status']})" for e in errors)
    console.say(f"    errors: {listed or 'none'}")
    console.say(f"    overall rationale: {draft['overall_rationale']}")
    console.say(
        f"    improved response: {'provided' if draft.get('improved_response') else 'none'}"
    )
    for warning in _consistency_warnings(draft):
        console.say(f"  CHECK: {warning}")


def annotate_response(
    console: Console,
    data_dir: Path,
    dataset: Dataset,
    response: CandidateResponse,
    reviewer_id: str,
    *,
    today: date,
    drafts: DraftStore,
    allow_repeat: bool = False,
) -> dict[str, Any] | None:
    """Run one evaluation. Returns the saved record, or None if the reviewer stopped.

    Raises ``EOFError`` / ``KeyboardInterrupt`` from the console unchanged; every answer
    given before that point is already in the draft.
    """
    if not allow_repeat and response.response_id in evaluated_response_ids(dataset, reviewer_id):
        raise AnnotationError(
            f"{reviewer_id} has already evaluated {response.response_id}; "
            "use --repeat only for a deliberate consistency re-review"
        )
    prompt = dataset.prompts_by_id[response.prompt_id]
    key = _evaluation_key(reviewer_id, response.response_id)
    draft = drafts.load(key)
    if draft is not None:
        console.say(f"\nResuming saved draft for {response.response_id}.")
    else:
        draft = {
            "kind": "evaluation",
            "response_id": response.response_id,
            "reviewer_id": reviewer_id,
            "scores": {},
            "score_rationales": {},
            "errors": [],
        }

    show_prompt(console, prompt)
    if not draft.get("response_revealed"):
        console.say("\nList the prompt's explicit and implicit requirements for yourself first.")
        console.ask("Press Enter to reveal the response: ")
        draft["response_revealed"] = True
        drafts.save(key, draft)
    show_response(console, response, f"RESPONSE (candidate {response.candidate_label})")
    show_reference_notes(console, prompt)

    while True:
        for dim in DIMENSIONS:
            if dim in draft["scores"]:
                continue
            score = _ask_score(console, dim)
            why = "Why was it not assessed?" if score is None else "Rationale"
            rationale = ask_text(console, f"  {why}")
            draft["scores"][dim] = score
            draft["score_rationales"][dim] = rationale
            drafts.save(key, draft)

        if not draft.get("errors_done"):
            console.say(
                "\nError labels: record each suspected or verified issue with its evidence."
            )
            while ask_yes_no(console, "Add an error label?", default=False):
                draft["errors"].append(_ask_error(console))
                drafts.save(key, draft)
            draft["errors_done"] = True
            drafts.save(key, draft)

        if "overall_rationale" not in draft:
            draft["overall_rationale"] = ask_text(console, "\nOverall rationale (1-3 sentences)")
            drafts.save(key, draft)
        if "improved_response" not in draft:
            draft["improved_response"] = ask_multiline(
                console, "Improved response (optional; do not invent facts you have not checked)"
            )
            drafts.save(key, draft)

        _show_evaluation_summary(console, draft)
        action = ask_choice(
            console,
            "Save? s=save, e=edit an item, q=quit and keep draft",
            {"s": "save", "e": "edit", "q": "quit"},
        )
        if action == "quit":
            console.say(f"Draft kept. Resume with the same command (draft: {drafts.path(key)}).")
            return None
        if action == "edit":
            _edit_item(console, draft)
            drafts.save(key, draft)
            continue
        break

    evaluation_id = next_id(data_dir / "evaluations.json", "evaluation_id", EVALUATION_ID_PREFIX)
    record = _evaluation_record(draft, response, reviewer_id, evaluation_id, today)
    _validate_and_append(data_dir / "evaluations.json", record, Evaluation, "evaluation_id")
    drafts.delete(key)
    console.say(f"Saved {evaluation_id} for {response.response_id}.")
    return record


def _edit_item(console: Console, draft: dict[str, Any]) -> None:
    items = {d: d for d in DIMENSIONS} | {
        "errors": "errors",
        "overall": "overall",
        "improved": "improved",
    }
    console.say(f"  Items: {', '.join(items)}")
    choice = ask_choice(console, "  Which item?", items)
    if choice in DIMENSIONS:
        draft["scores"].pop(choice, None)
        draft["score_rationales"].pop(choice, None)
    elif choice == "errors":
        draft["errors"] = []
        draft["errors_done"] = False
        console.say("  Error labels cleared; you will re-enter them.")
    elif choice == "overall":
        draft.pop("overall_rationale", None)
    else:
        draft.pop("improved_response", None)


def _validate_and_append(path: Path, record: dict[str, Any], schema: type, id_field: str) -> None:
    try:
        schema.model_validate(record)
    except ValidationError as exc:
        raise AnnotationError(f"record failed validation and was not saved: {exc}") from exc
    try:
        append_record(path, record, id_field)
    except StorageError as exc:
        raise AnnotationError(str(exc)) from exc


# --- pairwise preference ---------------------------------------------------------------------


def annotate_pair(
    console: Console,
    data_dir: Path,
    dataset: Dataset,
    pair: Pair,
    reviewer_id: str,
    *,
    today: date,
    drafts: DraftStore,
) -> dict[str, Any] | None:
    """Record one A/B/tie decision. Returns the saved record, or None if stopped."""
    if any(
        p.reviewer_id == reviewer_id
        and (p.response_a_id, p.response_b_id) == (pair.a.response_id, pair.b.response_id)
        for p in dataset.preferences
    ):
        raise AnnotationError(
            f"{reviewer_id} has already compared the pair for {pair.prompt.prompt_id}"
        )
    done = evaluated_response_ids(dataset, reviewer_id)
    missing = [r.response_id for r in (pair.a, pair.b) if r.response_id not in done]
    key = _preference_key(reviewer_id, pair.prompt.prompt_id)
    draft = drafts.load(key) or {"kind": "preference", "prompt_id": pair.prompt.prompt_id}

    show_prompt(console, pair.prompt)
    if missing:
        console.say(
            f"NOTE: you have not evaluated {', '.join(missing)} individually yet. "
            "Independent evaluations first reduce anchoring on the comparison."
        )
    show_response(console, pair.a, "RESPONSE A")
    show_response(console, pair.b, "RESPONSE B")
    show_reference_notes(console, pair.prompt)
    console.say(
        "\nDecide on substance. A/B are positions, not quality signals. Use tie when "
        "the difference would not matter to the user."
    )

    while True:
        if "winner" not in draft:
            draft["winner"] = ask_choice(
                console, "Better response", {"a": "A", "b": "B", "t": "tie"}
            )
            drafts.save(key, draft)
        if "reason" not in draft:
            draft["reason"] = ask_text(console, "Reason (name the decisive difference)")
            drafts.save(key, draft)
        console.say(f"\nDecision: {draft['winner']}  Reason: {draft['reason']}")
        action = ask_choice(
            console,
            "Save? s=save, e=edit, q=quit and keep draft",
            {"s": "save", "e": "edit", "q": "quit"},
        )
        if action == "quit":
            console.say(f"Draft kept. Resume with the same command (draft: {drafts.path(key)}).")
            return None
        if action == "edit":
            draft.pop("winner", None)
            draft.pop("reason", None)
            continue
        break

    preference_id = next_id(data_dir / "preferences.json", "preference_id", PREFERENCE_ID_PREFIX)
    record = {
        "schema_version": SCHEMA_VERSION,
        "preference_id": preference_id,
        "prompt_id": pair.prompt.prompt_id,
        "response_a_id": pair.a.response_id,
        "response_b_id": pair.b.response_id,
        "reviewer_id": reviewer_id,
        "annotation_source": "human",
        "winner": draft["winner"],
        "reason": draft["reason"],
        "rubric_version": RUBRIC_VERSION,
        "reviewed_at": today.isoformat(),
    }
    _validate_and_append(data_dir / "preferences.json", record, Preference, "preference_id")
    drafts.delete(key)
    console.say(f"Saved {preference_id} for {pair.prompt.prompt_id}.")
    return record
